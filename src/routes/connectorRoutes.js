const router = require('express').Router();
const { protect } = require('../middleware/auth');
const { allow } = require('../middleware/role');
const { requireTenant } = require('../middleware/tenant');
const dash = require('../controllers/dashboardController');
const connector = require('../controllers/connectorController');
const { upload: leadDocumentUpload } = require('../middleware/connectorDocumentUpload');
const leadValidator = require('../validators/connectorLeadValidator');
const submission = require('../controllers/loanSubmissionController');
const submissionValidator = require('../validators/loanSubmissionValidator');
const { validate } = require('../middleware/validate');
const { list } = require('../validators/listValidator');
router.use(protect, allow('connector'), requireTenant);
router.get('/dashboard', dash.connector);
router.get('/leads', connector.listLeads);
router.get('/applications', validate(list, 'query'), submission.list);
router.get('/applications/:id/documents/:documentId', submission.downloadDocument);
router.post('/leads', leadDocumentUpload, connector.createLead);
router.put('/leads/:id', leadDocumentUpload, connector.updateLead);
router.patch('/leads/:id/status', validate(leadValidator.status), connector.setLeadStatus);
router.get('/leads/:id/applications/:bankId/team', submission.teamOptions);
router.post('/leads/:id/applications', validate(submissionValidator.create), submission.create);
router.get('/leads/:id/documents/:docId', connector.downloadLeadDocument);
module.exports = router;
